#!/usr/bin/env bash
# Спільні функції для роботи з цілими числами. Підключати через source.

# is_int VALUE — код 0, якщо VALUE є цілим числом (необов'язковий мінус і цифри).
is_int() {
  [[ "$1" =~ ^-?[0-9]+$ ]]
}

# to_int VALUE — виводить ціле число без ведучих нулів (08 → 8, -007 → -7).
# VALUE має пройти is_int.
to_int() {
  if [[ "$1" == -* ]]; then
    echo $(( -10#${1#-} ))
  else
    echo $(( 10#$1 ))
  fi
}
